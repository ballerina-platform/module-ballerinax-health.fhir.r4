"""Generates model_info.bal (FHIR R4 type hierarchy and element types) for the FHIRPath engine.

Usage:
    curl -sSLO https://hl7.org/fhir/R4/definitions.json.zip
    unzip definitions.json.zip profiles-resources.json profiles-types.json
    python3 scripts/generate_model_info.py profiles-types.json profiles-resources.json > model_info.bal

Element type encoding (values of the per-path element maps):
    "date"                     single FHIR type
    "boolean|dateTime"         choice element (key is the name without [x])
    "System.String"            FHIRPath System type (e.g. Element.id, Extension.url)
    "#Questionnaire.item"      content reference to another element definition
A trailing "*" marks a repeating element (max cardinality > 1), e.g. "Coding*".
"""

